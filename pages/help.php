<h2>Getting help</h2>
<p>The student office answers records, fee and course questions on weekdays. Bring your student number and a photo ID.</p>
<ul class="list">
    <li>Records and transcripts: ground floor, North Hall.</li>
    <li>Fees and payments: ground floor, East Hall.</li>
    <li>Course changes: your faculty office.</li>
</ul>
<p>For urgent access problems, call the help desk and quote your student number.</p>
